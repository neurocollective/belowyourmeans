-- new schema

CREATE TABLE budget_user (
	id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	first_name text, 
	last_name text,
	email text,
	hashed_password text,
	create_date timestamp,
	modified_date timestamp,
	UNIQUE(email)
);

-- EAV table
CREATE TABLE user_preference_choice (
	id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	user_id int REFERENCES budget_user(id) NOT NULL,
	choice_key text,
	choice_value text
);

-- generic categories 
CREATE TABLE starter_budget_category (
	id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	display_name text NOT NULL,
	description text,
	create_date timestamp default now(),
	modified_date timestamp default now()
);

-- every user as the `starter_budget_category` values inserted into their specific `budget_category` rows
CREATE TABLE budget_category (
	id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	user_id int REFERENCES budget_user(id) default null, --nullable
	display_name text NOT NULL,
	description text,
	create_date timestamp default now(),
	modified_date timestamp default now()
);

-- entries to be associated with a category. Example - 
-- `budget_category_items.display_name = "Digital Card Purchase - NETFLIX COM LOS GATOS CA"` should 
-- relate to `category.dislay_name = "entertainment"`.
CREATE TABLE budget_category_items (
	category_id int REFERENCES budget_category(id) default null, --nullable
	display_name text NOT NULL,
	create_date timestamp default now(),
	modified_date timestamp default now(),
	PRIMARY KEY (category_id, display_name)
);

-- regex input to be associated with a category.
CREATE TABLE budget_category_pattern (
	id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	category_id int REFERENCES budget_category(id) default null, --nullable
	pattern text NOT NULL,
	create_date timestamp default now(),
	modified_date timestamp default now()
);

-- allow users to hide categories from their account
CREATE TABLE hidden_budget_category (
	id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	user_id int REFERENCES budget_user(id) NOT NULL,
	budget_category_id int REFERENCES budget_category(id) NOT NULL
);

-- just a way to group `budget_category_limit` entries. This allows user to switch between different budget concepts.
CREATE TABLE budget_concept (
	id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	user_id int REFERENCES budget_user(id) NOT NULL,
	name text NOT NULL
);

-- exists as monthly limits, but probably create 12 identitcal rows to start
CREATE TABLE budget_category_limit (
	id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	budget_concept_id int REFERENCES budget_concept(id),
	month_id int NOT NULL,
	dollar_allotment int NOT NULL
);

-- this is how you select by month in a timestamp:
